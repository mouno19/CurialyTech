import type { Entry, TokenSet } from "./registry";

// One look for a composed interface. Every component knows which of its colours play which role
// in its family (background, text, accent, series1…; component.json style.colors), so it can take
// another family's token set: each role's colour is swapped for the theme's colour of that role.
// A role colour with an alpha suffix (#60e6b222, a glow) becomes the theme colour with the same
// alpha. Colours a component uses that have no role (one-off shades) stay as they are.
// The theme itself is written once as CSS variables (--cx-*), for everything built around them.

const HEX = /#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?\b/g;

/** The component's source with its role colours taken from `theme` (unchanged when it is the same family). */
export function adaptSource(source: string, entry: Pick<Entry, "style">, theme: TokenSet | null): { source: string; swapped: number } {
  const family = entry.style?.tokens;
  const roles = entry.style?.colors ?? {};
  if (!theme || !family || family === theme.id || !Object.keys(roles).length) return { source, swapped: 0 };
  const map = new Map<string, string>();
  for (const [hex, role] of Object.entries(roles)) {
    const target = theme.colors[role];
    if (target && target.toLowerCase() !== hex.toLowerCase()) map.set(hex.toLowerCase(), target);
  }
  let swapped = 0;
  const out = source.replace(HEX, (whole, base: string, alpha: string | undefined) => {
    const target = map.get(`#${base.toLowerCase()}`);
    if (!target) return whole;
    swapped++;
    return `${target}${alpha ?? ""}`;
  });
  return { source: out, swapped };
}

/** The theme as CSS custom properties (and a matching chart series list). */
export function tokensCss(theme: TokenSet) {
  const lines = [`/* Design tokens: ${theme.name} (${theme.mode}). Generated by the Curialy component library. */`, ":root {"];
  for (const [role, value] of Object.entries(theme.colors)) lines.push(`  --cx-${role.replace(/([a-z])([0-9])/g, "$1-$2")}: ${value};`);
  for (const [role, value] of Object.entries(theme.fonts ?? {})) lines.push(`  --cx-font-${role}: ${value};`);
  for (const [role, value] of Object.entries(theme.radius ?? {})) lines.push(`  --cx-radius-${role}: ${value};`);
  if (theme.spacing) lines.push(`  --cx-gap: ${theme.spacing};`);
  lines.push(`  color-scheme: ${theme.mode};`, "}");
  lines.push(`body { background: var(--cx-background); color: var(--cx-text); font-family: var(--cx-font-sans); }`);
  return `${lines.join("\n")}\n`;
}

/** The theme for JavaScript (chart series colours in order, and every role). */
export function tokensModule(theme: TokenSet) {
  const series = Object.keys(theme.colors).filter(role => /^series\d$/.test(role)).sort().map(role => theme.colors[role]);
  return `// Design tokens: ${theme.name} (${theme.mode}). Generated by the Curialy component library.\nexport const tokens = ${JSON.stringify({ id: theme.id, mode: theme.mode, colors: theme.colors, fonts: theme.fonts, radius: theme.radius ?? {}, spacing: theme.spacing ?? null }, null, 2)};\nexport const series = ${JSON.stringify(series)};\n`;
}
